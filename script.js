/* pct(a, b) -> a as a rounded percentage of b. */
const pct = (a, b) => Math.round(a/b*100);

/* donut(items, bigNumber, smallLabel) -> HTML of a donut chart.
   The ring is drawn with SVG circles: each item gets an arc, with a small gap
   between arcs. The legend (name + %) is written under the ring. */
const donut = (it, big, sm) => {
  const R = 77.4,
  C = 2*Math.PI*R,
  G = 4.6,
  tot = it.reduce((x, y) => x+y.v, 0) || 1;
  let a = 0;
  const arcs = it.map(y => {
    const L = y.v/tot*C,
    d = `<circle cx="90" cy="90" r="${R}" fill="none" stroke-width="25.2" style="stroke:${y.c}" stroke-dasharray="${Math.max(L-G,1)} ${C}" stroke-dashoffset="${-(a+G/2)}"/>`;
    a += L;
    return d
  }).join("");
  return `<div><div class="dn"><svg width="180" height="180" viewBox="0 0 180 180" style="transform:rotate(-90deg)">${arcs}</svg><span>${big}<small>${sm}</small></span></div><div class="lg">${it.map(y=>`<div><i style="background:${y.c}"></i>${y.l} ${pct(y.v,tot)}%</div>`).join("")}</div></div>`
};

/* cols(items, gap, barWidth, fontSize) -> HTML of a column chart.
   Each column = value on top, bar (height scaled to the highest value, max 170px), label. */
const cols = (it, g, bw, fs) => {
  const m = Math.max(...it.map(y => y.v), 1);
  return `<div class="cols" style="gap:${g}px;--bw:${bw}px">${it.map(y=>`<div style="font-size:${fs}px"><b>${y.v}</b><i style="height:${Math.max(16,Math.round(y.v/m*170))}px;background:${y.c}"></i>${y.l}</div>`).join("")}</div>`
};

/* dayView(prefix, sites) -> fills the dashboard cards.
   prefix "g" = global dashboard (index.html), prefix "d" = daily overview (import.html).
   It fills: availability card, "Sites by status" card, "Top 5 wilayas" card. */
function dayView(p = "d", D = S) {
  const sfx = p === "g" ? "global" : "this import",
  set = (id, t) => {
    const e = $(id);
    if (e)e.textContent = t
  };
  set(p+"day", dayL());
  set(p+"file", `${cur.name} · imported ${fmt(cur.ts)} · ${D.length.toLocaleString()} sites`);
  /* Split the sites: working / not working, count each condition, count critical sites per wilaya. */
  const W = D.filter(x => !x.down),
  n = W.length,
  dn = D.length-n,
  c = {
    crit: 0,
    med: 0,
    good: 0
  },
  wc = {},
  all = {};
  D.forEach(x => all[x.w] = (all[x.w] || 0)+1);
  W.forEach(x => {
    const k = cond(x.load);
    c[k]++;
    if (k === "crit")wc[x.w] = (wc[x.w] || 0)+1
  });
  const H = t => `<b style="font-size:18px">${t[0]}</b><p class="sub" style="font-size:13px">${t[1]}</p>`;
  /* Availability card: total, working, not working and the blue/grey bar. */
  $(p+"av").innerHTML = `<div><small class="mu">Total sites</small><b>${D.length.toLocaleString()}</b></div><div><small class="mu">Working</small><b>${n.toLocaleString()}</b><span style="color:var(--blue);font-weight:600;font-size:12px">${pct(n,D.length)}% operational</span></div><div><small class="mu">Not working</small><b>${dn.toLocaleString()}</b><span class="c-down" style="font-weight:600;font-size:12px">${pct(dn,D.length)}% down</span></div>`;
  $(p+"st").innerHTML = `<i style="width:${n/D.length*100}%;background:var(--blue)"></i><i style="flex:1;background:var(--down)"></i>`;
  /* "Sites by status" card: donut, columns and the breakdown tiles (critical / medium / good). */
  const cs = [{
    l: "Critical",
    v: c.crit,
    c: "var(--crit)"
  }, {
    l: "Medium",
    v: c.med,
    c: "var(--med)"
  }, {
    l: "Good",
    v: c.good,
    c: "var(--good)"
  }],
  R = ["80–100% load", "50–80% load", "0–50% load"];
  const tile = (y, r) => `<div class="tile"><i style="background:${y.c}"></i><div style="flex:1"><b>${y.l}</b><br><span class="mu" style="font-size:12px">${r}</span></div><div style="text-align:right"><b>${y.v.toLocaleString()} sites</b><br><span style="color:${y.c};font-size:12px">${pct(y.v,n)}% of network</span></div></div>`;
  $(p+"ss").innerHTML = H(["Sites by status", "Number & share of working sites · "+sfx])+`<div class="cc">${donut(cs,n.toLocaleString(),"sites")}${cols(cs,28,56,12)}<div class="dp"><small class="mu">BREAKDOWN</small>${cs.map((y,k)=>tile(y,R[k])).join("")}</div></div>`;
  /* "Top 5 wilayas" card: five wilayas with the most critical sites, one red shade each. */
  const SH = ["#b42318", "#e5352b", "#f04438", "#f97066", "#fda29b"];
  const top = Object.entries(wc).sort((a, b) => b[1]-a[1]).slice(0, 5).map((e, k) =>({
    l: e[0],
    v: e[1],
    c: SH[k]
  }));
  const rows = top.map(y => {
    const r = pct(y.v, all[y.l]);
    return `<div class="rw"><b>${y.l}</b><b class="c-crit">${y.v}</b><span class="mu">${all[y.l]}</span><span style="display:flex;align-items:center;gap:8px"><span class="track" style="min-width:0;flex:1"><i style="width:${Math.min(100,r*2.5)}%;background:${y.c}"></i></span><b>${r}%</b></span></div>`
  }).join("");
  $(p+"ww").innerHTML = H(["Top 5 wilayas · critical sites", "Wilayas with the most critical sites (80–100% load) · "+sfx])+`<div class="cc">${donut(top,top.reduce((a,y)=>a+y.v,0),"critical sites")}${cols(top,16,44,11)}<div class="dp"><small class="mu">CRITICAL RATE PER WILAYA</small><div><div class="rw h"><span>WILAYA</span><span>CRITICAL</span><span>TOTAL SITES</span><span>RATE</span></div>${rows}</div><small class="mu">Rate = critical sites ÷ total sites in the wilaya</small></div></div>`
}

