/* renderSite(site) -> fills site.html: details, load summary, load graph, fixed report. */
function renderSite(s) {
  const c = condS(s);
  $("dcr").textContent = s.id;
  $("dt").textContent = s.id;
  $("ds").textContent = `${s.w} · ${LBL[c]}`;
  const K = [["Site ID", s.id], ["Wilaya", s.w], ["Condition", `<span class="c-${c}">${LBL[c]}</span>`], ["NE type", s.ne], ["Entity type", s.et], ["Measure point", s.mp], ["End time", fmt(s.d)]];
  if (s.fc)K.push(["Failure cause", s.fc]);
  $("dg").innerHTML = K.map(k => `<div class="k"><small>${k[0]}</small><b>${k[1]}</b></div>`).join("");
  const v = s.h.filter(x => x>0),
  f = n => v.length ? n+"%" : "—";
  $("dl").innerHTML = [["Average load", f(Math.round(v.reduce((a, b) => a+b, 0)/(v.length || 1)))], ["Maximum load", f(Math.max(...v))], ["Minimum load", f(Math.min(...v))]].map(k => `<div class="k"><small>${k[0]}</small><b>${k[1]}</b></div>`).join("");
  /* Load graph (SVG): width/height and margins, then the x (day) and y (percent) scales. */
  const GW = 700,
  GH = 260,
  GL = 44,
  GR = 20,
  GT = 20,
  GB = 36,
  X = i => GL+i*(GW-GL-GR)/6,
  Y = v => GT+(100-v)/100*(GH-GT-GB);
  const DL = s.h.map((x, i) => {
    const d = new Date(s.d);
    d.setDate(d.getDate()-(6-i));
    return `${d.getDate()} ${MO[d.getMonth()]}`
  });
  let gg = [0, 20, 40, 60, 80, 100].map(t => `<line x1="${GL}" x2="${GW-GR}" y1="${Y(t)}" y2="${Y(t)}" style="stroke:var(--bd)"/><text x="${GL-8}" y="${Y(t)+4}" text-anchor="end">${t}%</text>`).join("");
  gg += [[50, "med"], [80, "crit"]].map(([t, k]) => `<line x1="${GL}" x2="${GW-GR}" y1="${Y(t)}" y2="${Y(t)}" stroke-dasharray="4 4" style="stroke:var(--${k})"/>`).join("");
  const pts = s.h.map((x, i) => `${X(i)},${Y(x)}`).join(" ");
  const dots = s.h.map((x, i) => {
    const off = s.down && i === 6,
    k = off ? "down" : cond(x);
    return `<circle cx="${X(i)}" cy="${Y(x)}" r="5" style="fill:var(--${k});stroke:var(--bg);stroke-width:2"/><text x="${X(i)}" y="${Y(x)-11}" text-anchor="middle" style="fill:var(--tx);font-weight:600">${off?"Off":x+"%"}</text><text x="${X(i)}" y="${GH-12}" text-anchor="middle">${DL[i]}</text>`
  }).join("");
  $("dh").innerHTML = `<svg viewBox="0 0 ${GW} ${GH}" width="100%" role="img" aria-label="Load by day, in percent">${gg}<polyline points="${pts}" fill="none" style="stroke:var(--blue)" stroke-width="2.5" stroke-linejoin="round" stroke-linecap="round"/>${dots}</svg>`;
  /* The fixed report: one text for each condition (critical, medium, good, not working). */
  const RP = {
    crit: "Critical load. This site is running at 80% or more of its capacity and is close to saturation, which can cause congestion and a poorer service for users. Recommended actions: review the recent traffic growth, plan a capacity upgrade or load balancing with neighboring sites, and follow this site daily until its load goes back below 80%.",
    med: "Medium load. This site is working normally (50–80% of its capacity) but has limited room left. Recommended actions: keep monitoring the load trend over the coming days and include the site in capacity planning if the load keeps rising.",
    good: "Good load. This site is below 50% of its capacity and has enough room for the current traffic. No action is needed; keep the routine monitoring.",
    down: "Site not working. This site is out of service and carries no traffic. Recommended actions: check the failure cause above, send a field team if needed, and restore the service as soon as possible. Neighboring sites may take extra traffic until it is back."
  };
  $("rp").textContent = LBL[c];
  $("rp").style.background = `var(--${c})`;
  $("rt").textContent = RP[c];
}

/* initSite() -> finds the site from ?id=... and shows it.
   The "back" links return to the list of the same import. */
function initSite() {
  const s = S.find(x => x.id === Q.get("id"));
  /* Opened from the dashboard lists (?from=dash): "back" goes to the dashboard.
     Otherwise "back" goes to the list of sites of the same import. */
  const fromDash = Q.get("from") === "dash";
  document.querySelectorAll("[data-back]").forEach(a => {
    a.href = fromDash ? "index.html" : "sites.html"+tq;
    a.textContent = fromDash ? a.textContent.replace("All sites", "Dashboard").replace("Back to all sites", "Back to dashboard") : a.textContent
  });
  if (!s) {
    $("dt").textContent = "Site not found";
    return
  }
  renderSite(s)
}

