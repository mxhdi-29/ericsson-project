/* WL = the wilayas used in the demo data: [site code prefix, wilaya name].
   The prefix is the start of every site ID (ALG-0001 is a site of Algiers). */
const WL = [["ALG", "Algiers"], ["ORN", "Oran"], ["CON", "Constantine"], ["BLI", "Blida"], ["SET", "Sétif"], ["TIZ", "Tizi Ouzou"], ["ANN", "Annaba"], ["BAT", "Batna"], ["BEJ", "Béjaïa"], ["TLM", "Tlemcen"], ["MOS", "Mostaganem"], ["GHA", "Ghardaïa"]];

/* Small seeded random number generator. The same seed always gives the same
   sites, so every page shows the same data without any server or database. */
let seed = 7;
const rnd = () => {
  seed = (seed*16807)%2147483647;
  return seed/2147483647
};

/* Month names used when a date is written ("1 Oct 2026"). */
const MO = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

/* fmt(date) -> "1 Oct 2026 · 09:15" (day, month, year, hour). */
const fmt = d => `${d.getDate()} ${MO[d.getMonth()]} ${d.getFullYear()} · ${String(d.getHours()).padStart(2,"0")}:${String(d.getMinutes()).padStart(2,"0")}`;

/* iso(date) -> "2026-10-01", the format of the date filter field. */
const iso = d => `${d.getFullYear()}-${String(d.getMonth()+1).padStart(2,"0")}-${String(d.getDate()).padStart(2,"0")}`;

/* cond(percent) -> status of a site from its load, using the project thresholds:
   0-50% good (green), 50-80% medium (orange), 80-100% critical (red). */
const cond = p => p >= 80 ? "crit" : p >= 50 ? "med" : "good";

/* LBL = the text shown for each status. */
const LBL = {
  crit: "Critical",
  med: "Medium",
  good: "Good",
  down: "Not working"
};

/* condS(site) -> same as cond(), but a site that is not working is always "down" (grey). */
const condS = s => s.down ? "down" : cond(s.load);

/* gen(seed) -> builds the list of 1,500 demo sites.
   Each site has: id, wilaya, load (%), last update (d), NE type (ne), entity type (et),
   measure point (mp), failure cause (fc, only if not working) and the load of the
   last 7 days (h). About 17% of the sites are "not working".
   To use real data later, replace this function with the code that reads the imported file. */
function gen(sd) {
  seed = sd;
  const S = [];
  for (let i = 0; i<1500; i++) {
    const w = WL[i%12];
    const d = new Date(2026, 8, 30-Math.floor(rnd()*4), Math.floor(rnd()*24), Math.floor(rnd()*12)*5);
    S.push({
      id: `${w[0]}-${String(Math.floor(i/12)+1).padStart(4,"0")}`,
      w: w[1],
      load: 1+Math.floor(rnd()*99),
      down: rnd()<.173,
      d,
      ne: rnd()>.5 ? "eNodeB" : "gNodeB",
      et: ["Cell", "Sector", "Carrier"][Math.floor(rnd()*3)],
      mp: rnd()>.5 ? "PRB utilization" : "Traffic load",
      tech: rnd()>.5 ? "4G + 5G" : "4G",
      cells: 3+Math.floor(rnd()*9),
      bw: [20, 40, 60, 100][Math.floor(rnd()*4)],
      pw: rnd()>.3 ? "Mains + battery" : "Mains + generator",
      bh: rnd()>.5 ? "Fiber" : "Microwave",
      yr: 2014+Math.floor(rnd()*11),
      up: (97+rnd()*2.9).toFixed(2),
      lat: (28+rnd()*8).toFixed(4),
      lng: (rnd()*8-1).toFixed(4),
      h: Array.from({
        length: 7
      }, () => 0)
    });
  }
  const FC = ["Power failure", "Backhaul link down", "Hardware fault", "Software crash"];
  S.forEach(s => {
    s.fc = s.down ? FC[Math.floor(rnd()*4)] : "";
    if (s.down)s.load = 0;
    let v = s.down ? 40 : s.load;
    s.h = s.h.map((_, k) => k === 6 ? s.load : (v = Math.min(99, Math.max(1, v+Math.round((rnd()-.5)*24)))))
  });
  return S
}

