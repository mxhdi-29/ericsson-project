/* gLists(sites) -> the two lists under the dashboard cards: top 10 critical sites
   and bottom 10 near-empty sites (only working sites), with their buttons.
   Every row is clickable: the site ID is a link and a click on the row opens
   site.html?id=<site ID>&from=dash, the page with all the information of that site
   (from=dash makes its "back" links return to the dashboard). */
function gLists(D) {
  /* Split the sites: working / not working, count each condition, count critical sites per wilaya. */
  const W = D.filter(x => !x.down),
  hi = [...W].sort((a, b) => b.load-a.load).slice(0, 10),
  lo = [...W].sort((a, b) => a.load-b.load).slice(0, 10);
  const tb = (t, sub, col, a, btn, id) => `<b style="font-size:18px"><i style="display:inline-block;width:12px;height:12px;border-radius:50%;background:${col};margin-right:10px"></i>${t}</b><p class="sub" style="font-size:13px;margin:4px 0 12px">${sub}</p><div class="tw"><table style="min-width:420px"><thead><tr><th>#</th><th>SITE ID</th><th>WILAYA</th><th style="width:30%">LOAD</th><th class="r">%</th></tr></thead><tbody>${a.map((x,i)=>{const c=cond(x.load);return `<tr class="go" data-href="site.html?id=${x.id}&from=dash"><td class="mu">${i+1}</td><td class="b"><a class="sl" href="site.html?id=${x.id}&from=dash">${x.id}</a></td><td class="mu">${x.w}</td><td><div class="track"><i style="width:${x.load}%;background:var(--${c})"></i></div></td><td class="r b c-${c}">${x.load}%</td></tr>`}).join("")}</tbody></table></div><div style="margin-top:16px"><a class="btn" href="${id}">${btn} →</a></div>`;
  $("gtop").innerHTML = tb("Top 10 critical sites", "Highest load · 80–100% shown in red", "var(--crit)", hi, "View all critical sites", "critical.html");
  $("gbot").innerHTML = tb("Bottom 10 · near empty", "Lowest load · 0–50% shown in green", "var(--good)", lo, "View all near-empty sites", "sites.html?c=good&sort=asc");
  /* Click on a row (anywhere except the ID link, which already works) -> open that site's page. */
  [$("gtop"), $("gbot")].forEach(card => card.addEventListener("click", e => {
    const row = e.target.closest("tr[data-href]");
    if (row && !e.target.closest("a")) location.href = row.dataset.href
  }))
}

