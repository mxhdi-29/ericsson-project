/* addH(record) -> adds an import to the history and saves it in the browser.
   A record: n = file name, t = time (ms), s = data seed, ok = success, c = sites count, e = error. */
function addH(r) {
  HIST.unshift(r);
  try {
    localStorage.setItem(HK, JSON.stringify(HIST.slice(0, 200)))
  } catch (e) {}
}

